# ---------------------------------------------------------------- build

def build_mats(spec):
    cache = {}
    codes = {'E': (EYE, 0), 'P': (BLUSH, None)} if True else {}
    for ch, v in spec.items():
        base, lvl = v[0], v[1]
        mode = v[2] if len(v) > 2 else 'cyl'
        key = (base, mode)
        if key not in cache:
            cache[key] = Mat(base, mode)
        codes[ch] = (cache[key], lvl)
    return codes

def apply_legs(g, legs, frame, walking):
    top, bt = legs['top'], legs['boot_top']
    nx, nw = legs['near']
    fx, fw = legs['far']
    bw = legs['boot_w']
    robe = legs.get('robe', False)
    # walking offsets (near, far) in x, and lift
    if walking:
        offs = [(1, -1), (0, 0), (-1, 1), (0, 0)][frame]
        lift = [(1, 0), (0, 0), (0, 1), (0, 0)][frame]
    else:
        offs, lift = (0, 0), (0, 0)
    for leg, (x0, w), off, lf in (('far', (fx, fw), offs[1], lift[1]), ('near', (nx, nw), offs[0], lift[0])):
        if not robe:
            for y in range(top, bt):
                # upper leg shifts half, lower full
                t = (y - top) / max(1, bt - top)
                o = round(off * t)
                for x in range(x0 + o, x0 + o + w):
                    if g[y][x] == '.':
                        g[y][x] = 'S'
        for y in range(bt, 46):
            yy = y - lf
            for x in range(x0 + off - (1 if leg == 'near' else 0), x0 + off - (1 if leg == 'near' else 0) + bw):
                if 0 <= yy < H and g[yy][x] in '.S':
                    g[yy][x] = 'B'

def render_frame(name, frame=0, walking=False):
    d = DESIGNS[name]
    g = new_grid(W, H)
    if d['back']:
        d['back'](g, frame)
    stamp(g, d['art'])
    apply_legs(g, d['legs'], frame, walking)
    if d['extra']:
        d['extra'](g, frame)
    arr = render(g, build_mats(d['mats']))
    if walking and frame in (1, 3):
        # bob: upper body up 1px (everything above leg top)
        arr = shift_rows(arr, 0, d['legs']['top'], -1)
    return arr

def idle_frames(name):
    a = render_frame(name, 0, False)
    top = DESIGNS[name]['legs']['top']
    b = shift_rows(a, 0, top - 4, 1)
    return [a, b]

def walk_frames(name):
    return [render_frame(name, i, True) for i in range(4)]

