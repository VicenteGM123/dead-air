def put(g, x, y, ch):
    if 0 <= y < len(g) and 0 <= x < len(g[0]):
        g[y][x] = ch

def vline(g, x, y0, y1, ch):
    for y in range(y0, y1 + 1):
        put(g, x, y, ch)

def hline(g, x0, x1, y, ch):
    for x in range(x0, x1 + 1):
        put(g, x, y, ch)

