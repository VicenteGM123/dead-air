def make_jar(icon, tint):
    g = new_grid(18, 19)
    stamp(g, JAR)
    mats = {'G': ('#cfe6ee', None, 'flat'), 'h': ('#ffffff', None, 'flat'), 'C': ('#9a6a42', None), 'x': (tint, None, 'flat')}
    cache, codes = {}, {}
    for ch, v in mats.items():
        m = Mat(v[0], v[2] if len(v) > 2 else 'cyl')
        codes[ch] = (m, v[1])
    jar = render(g, codes)
    # glass interior: tinted translucent, then the icon composited inside
    inside = jar.copy()
    mask = np.zeros(inside.shape[:2], bool)
    for y in range(19):
        for x in range(18):
            if g[y][x] == 'x':
                mask[y, x] = True
    t = hexrgb(tint)
    inside[mask, :3] = (np.array(t) * 0.35 + np.array([40, 46, 70]) * 0.65).astype(np.uint8)
    inside[mask, 3] = 210
    # paste icon (16x16) scaled into interior area 14x14: crop 1px border
    ic = icon[1:15, 1:15]
    for y in range(14):
        for x in range(14):
            if ic[y, x, 3] > 0 and mask[4 + y, 2 + x]:
                inside[4 + y, 2 + x] = ic[y, x]
    out = np.zeros((22, 18, 4), np.uint8)
    out[3:22] = inside
    return out

