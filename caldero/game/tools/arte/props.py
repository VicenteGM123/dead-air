def art(spec, mats, w=None, h=None, outline=True, light='left'):
    rows = spec.strip('\n').split('\n')
    W = w or max(len(r) for r in rows)
    H = h or len(rows)
    g = new_grid(W, H)
    stamp(g, spec)
    cache, codes = {}, {}
    for ch, v in mats.items():
        base, lvl = v[0], v[1]
        mode = v[2] if len(v) > 2 else 'cyl'
        key = (base, mode)
        if key not in cache:
            cache[key] = Mat(base, mode)
        codes[ch] = (cache[key], lvl)
    return render(g, codes, outline=outline, light_from=light)

def pad_to(arr, w, h, anchor='bottom'):
    out = np.zeros((h, w, 4), dtype=np.uint8)
    ah, aw = arr.shape[:2]
    x = (w - aw) // 2
    y = h - ah if anchor == 'bottom' else (h - ah) // 2
    out[y:y+ah, x:x+aw] = arr
    return out

