import sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from smodel import *

def fmt(v):
    s = f"{float(v):.3f}".rstrip("0").rstrip(".")
    return "0.0" if s in ("", "-0") else (s if "." in s else s + ".0")

def arr(a):
    return "[" + ", ".join(fmt(x) for x in a) + "]"

def export(strikes, path=os.path.join(HERE, "strike_data.gd.txt")):
    """strikes: {name: S}; S has len/in/out/ev + curves (and optional 'feet' plan dict)"""
    out = []
    out.append("## The raw definitions: curves [t, value, ...] per joint, in degrees and metres (see _strike_pose for the names).")
    out.append("## GENERATED by design/*.py (docs/ANIMATION.md section 4.8): the key poses were solved for the blade's path, the timings")
    out.append("## set so the joints peak in the order of the kinetic chain.")
    out.append("static func _strike_raw(nm: String) -> Dictionary:")
    out.append("\tmatch nm:")
    for nm, S in strikes.items():
        out.append(f'\t\t"{nm}":')
        out.append(f'\t\t\treturn {{"len": {fmt(S["len"])}, "in": {fmt(S["in"])}, "out": {fmt(S["out"])}, "ev": {gd_ev(S["ev"])},')
        keys = [k for k in S if k not in ("len", "in", "out", "ev", "feet", "pivot", "doc")]
        for j, k in enumerate(keys):
            tail = "," if j < len(keys) - 1 else ""
            val = arr(S[k]) if isinstance(S[k], (list, tuple, np.ndarray)) else fmt(S[k])
            out.append(f'\t\t\t\t"{k}": {val}{tail}')
        feet = S.get("feet")
        if feet is not None:
            out[-1] += ","
            out.append(f'\t\t\t\t"feet": {gd_any(feet)}')
        out[-1] += "}"
    out.append("\treturn {}")
    out.append("")
    out.append("")
    out.append("## The strikes that are built from joint angles (the others still play their keys).")
    out.append("const STRIKE_NAMES := [" + ", ".join(f'"{n}"' for n in strikes) + "]")
    open(path, "w").write("\n".join(out) + "\n")
    print("exported", list(strikes), "->", path)

def gd_any(v):
    if isinstance(v, dict):
        return "{" + ", ".join(f'"{k}": {gd_any(x)}' for k, x in v.items()) + "}"
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(gd_any(x) for x in v) + "]"
    if isinstance(v, str):
        return f'"{v}"'
    if isinstance(v, (bool, np.bool_)):
        return "true" if v else "false"
    if isinstance(v, (int, np.integer)):
        return str(int(v))
    if isinstance(v, (float, np.floating)):
        return fmt(v)
    return str(v)
